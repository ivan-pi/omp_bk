#!/usr/bin/env python3
"""slm_pad_search.py -- choose padded SLM strides for the seven-step BK1 kernel.

The kernel (openmp/offload/bk1_offload/grid_inline.h, sycl/bk1_sycl.cpp) passes data
between its steps through five intermediate boxes, each a 4-d array
(element, a, b, c) with c contiguous:
  A  s2 -> s3   (e, p, j, k)  extents (nq, nm, nm)
  B  s3 -> s4   (e, q, p, k)  extents (nq, nq, nm)
  C  s4 -> s6   (e, r, q, p)  extents (nq, nq, nq)
  D  s6 -> s7   (e, k, q, p)  extents (nm, nq, nq)
  E  s7 -> s8   (e, k, j, p)  extents (nm, nm, nq)
For each box the b stride is nc + db, the a stride nb * Sb + da and the element
stride na * Sa + de, with db, da, de in 0..3.  A SIMD16 sub-group is 16
consecutive work-items of the step's flattened index; SLM has 16 banks of
4 bytes, and distinct addresses in one bank serialize.  The search picks per
box the padding that minimizes the worst conflict degree of its write plus its
read (summed over the loop index), keeping the box within 25% more floats.

usage:  slm_pad_search.py [nq:batch ...]   (default: the best batch per order)
Prints the per-box strides as a C++ table and the conflict degree before/after.
"""
import itertools
import sys

BEST = {3: 16, 4: 4, 5: 4, 6: 1, 7: 1, 8: 1, 9: 1, 10: 4}


def decode(t, dims):
    out = []
    for d in reversed(dims):
        out.append(t % d)
        t //= d
    return list(reversed(out))


def ways(n, dims, loop, addr, sg=16):
    """sum over loop indices of the worst bank multiplicity over sub-groups"""
    total = 0
    for l in range(loop):
        worst = 1
        for s0 in range(0, n, sg):
            banks = {}
            for t in range(s0, min(s0 + sg, n)):
                a = addr(*decode(t, dims), l)
                banks.setdefault(a % 16, set()).add(a)
            worst = max(worst, max(len(v) for v in banks.values()))
        total += worst
    return total


def boxes(nq, b):
    nm = nq - 1
    # (name, extents (na, nb, nc), writer (n, dims, loop, map), reader (n, dims, loop, map))
    # map(lane coords..., loop index) -> (e, a, b, c) box coordinates
    return [
        ("A", (nq, nm, nm),
         (b * nm * nm, (b, nm, nm), nq, lambda e, j, k, p: (e, p, j, k)),
         (b * nq * nm, (b, nq, nm), nm, lambda e, p, k, j: (e, p, j, k))),
        ("B", (nq, nq, nm),
         (b * nq * nm, (b, nq, nm), nq, lambda e, p, k, q: (e, q, p, k)),
         (b * nq * nq, (b, nq, nq), nm, lambda e, q, p, k: (e, q, p, k))),
        ("C", (nq, nq, nq),
         (b * nq * nq, (b, nq, nq), nq, lambda e, q, p, r: (e, r, q, p)),
         (b * nq * nq, (b, nq, nq), nq, lambda e, q, p, r: (e, r, q, p))),
        ("D", (nm, nq, nq),
         (b * nq * nq, (b, nq, nq), nm, lambda e, q, p, k: (e, k, q, p)),
         (b * nm * nq, (b, nm, nq), nq, lambda e, k, p, q: (e, k, q, p))),
        ("E", (nm, nm, nq),
         (b * nm * nq, (b, nm, nq), nm, lambda e, k, p, j: (e, k, j, p)),
         (b * nm * nm, (b, nm, nm), nq, lambda e, j, k, p: (e, k, j, p))),
    ]


def strides(ext, pad):
    na, nb, nc = ext
    db, da, de = pad
    sb = nc + db
    sa = nb * sb + da
    se = na * sa + de
    return se, sa, sb


def cost(nq, b, box, pad):
    name, ext, wr, rd = box
    se, sa, sb = strides(ext, pad)
    total = 0
    for n, dims, loop, m in (wr, rd):
        def addr(*args, m=m):
            e, a, bb, c = m(*args)
            return e * se + a * sa + bb * sb + c
        total += ways(n, dims, loop, addr)
    return total, se


def main():
    pairs = [tuple(int(x) for x in a.split(":")) for a in sys.argv[1:]] or sorted(BEST.items())
    rows = []
    for nq, b in pairs:
        dense = 1
        for box in boxes(nq, b):
            dense *= 1
        entry = []
        before = after = 0
        for box in boxes(nq, b):
            ext = box[1]
            base, _ = cost(nq, b, box, (0, 0, 0))
            limit = 1.25 * ext[0] * ext[1] * ext[2]
            best = min(((cost(nq, b, box, pad)[0], sum(pad), pad) for pad in itertools.product(range(4), repeat=3)
                        if strides(ext, pad)[0] <= limit), key=lambda x: (x[0], x[1]))
            before += base
            after += best[0]
            entry.append((box[0], strides(ext, best[2]), base, best[0]))
        rows.append((nq, b, entry, before, after))
    print("// generated by scripts/study/slm_pad_search.py: {element, a, b} strides per box")
    for nq, b, entry, before, after in rows:
        s = ", ".join("{%d, %d, %d}" % st for _, st, _, _ in entry)
        print(f"// nq = {nq}, batch {b}: conflict sum {before} -> {after}  " +
              " ".join(f"{n}:{c0}->{c1}" for n, _, c0, c1 in entry))
        print(f"    {{{nq}, {{{s}}}}},")


if __name__ == "__main__":
    main()
